#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const { legacyRoutes } = require('../src/routes');

const OUT = path.join(__dirname, '..', 'deploy', 'redirects.conf');
const HEADER = '# Generated by scripts/gen-redirects.js from src/routes.js. Do not edit.\n';

function render() {
  return HEADER + legacyRoutes.map(function(r) {
    return 'rewrite ' + r.source + ' ' + r.target + ' permanent;';
  }).join('\n') + '\n';
}

const content = render();
const check = process.argv.includes('--check');

if (check) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf-8') : '';
  if (current !== content) {
    console.error('redirects.conf is out of date — run npm run gen:redirects');
    process.exit(1);
  }
  console.log('redirects.conf: no drift');
  process.exit(0);
}

fs.writeFileSync(OUT, content, 'utf-8');
console.log('Wrote ' + path.relative(path.join(__dirname, '..'), OUT));
