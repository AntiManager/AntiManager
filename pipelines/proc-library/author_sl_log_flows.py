    # normalise: drop an existing flow section
    idx = text.find("\r\n" + HEADER)
    if idx == -1:
        idx = text.find("\n" + HEADER)
    if idx != -1:
        text = text[:idx].rstrip("\r\n") + "\r\n"
    if not text.endswith("\r\n\r\n"):
        text = text.rstrip("\r\n") + "\r\n\r\n"
    text += build_section()
