# --- pass 3: role vocabulary normalisation (within Исполнитель/Владелец) -----
ROLE_ATTR = re.compile(
    r"(?m)^(\s*[-*]?\s*\*\*(?:Исполнитель|Владелец):\*\*\s*)([^\r\n]*)")
ROLE_REPS = [
    (r"(?i)\bНачальник ТС\b", "Начальник транспортной службы"),
    (r"(?i)\bРуководитель СК\b", "Руководитель складского комплекса"),
    (r"(?i)\bначальник СК\b", "Начальник складского комплекса"),
    (r"(?i)\s*\(ИПП\)", ""),
    (r"(?i)\bИПП\b", "Инженер по подготовке производства"),
    (r"(?i)\bСпециалист по ОТ\b", "Специалист по охране труда"),
    (r"(?i)\bОтветственный за ПБ\b", "Ответственный за промышленную безопасность"),
    (r"(?i)\bСпециалист по развитию ПС\b", "Специалист по развитию производственной системы"),
    (r"(?i)экономист ПЭО\b", "экономист планово-экономической службы"),
    (r"\(ПЭО\)", "(планово-экономическая служба)"),
    (r"\bПЭО\b", "планово-экономическая служба"),
    (r"\bПЭУ\b", "планово-экономическая служба"),
]


def _cap_top(v: str) -> str:
    """Capitalise the first letter of the value and of every top-level ` / `/`; `
    segment, leaving text inside parentheses untouched."""
    out, depth, need_cap, j = [], 0, True, 0
    while j < len(v):
        ch = v[j]
        if need_cap and ch.isalpha():
            ch = ch.upper()
            need_cap = False
        if ch == "(":
            depth += 1
            need_cap = False
        elif ch == ")":
            depth = max(0, depth - 1)
        out.append(ch)
        if depth == 0 and (v.startswith(" / ", j) or v.startswith("; ", j)):
            need_cap = True
        j += 1
    return "".join(out)


def norm_role(v: str) -> str:
    for pat, rep in ROLE_REPS:
        v = re.sub(pat, rep, v)
    return _cap_top(v)


def transform(name: str, text: str):
    n_sub = 0
    for f, old, new in SUBS:
        if f == name and old in text:
            text = text.replace(old, new)
            n_sub += 1
    n_del = 0
    if name in DELETE_PREFIX:
        pref = DELETE_PREFIX[name]
        lines = text.splitlines(keepends=True)
        kept = [ln for ln in lines if not ln.lstrip().startswith(pref)]
        n_del = len(lines) - len(kept)
        text = "".join(kept)
    n_role = 0

    def _repl(m):
        nonlocal n_role
        val = m.group(2)
        core = val.rstrip()
        tail = val[len(core):]
        new = norm_role(core)
        if new != core:
            n_role += 1
        return m.group(1) + new + tail

    text = ROLE_ATTR.sub(_repl, text)
    return text, n_sub, n_del, n_role


def main(argv=None):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    argv = sys.argv[1:] if argv is None else argv
    apply = "--apply" in argv

    if not VAULT or not os.path.isdir(LIB):
        print("ERROR: set PROC_LIB_VAULT to the 'Библиотека процессов' folder")
        return 2
    files = sorted(f for f in os.listdir(LIB) if f.endswith(".md"))
    planned, total = [], [0, 0, 0]
    changed = {}
    for fn in files:
        raw = io.open(os.path.join(LIB, fn), "rb").read()
        text = raw.decode("utf-8")
        new, a, b, c = transform(fn, text)
        if (a, b, c) != (0, 0, 0):
            planned.append((fn, a, b, c))
            total[0] += a; total[1] += b; total[2] += c
            changed[fn] = new

    print("planned changes (subs / deleted-lines / roles):")
    for fn, a, b, c in planned:
        print(f"  {fn:12} subs={a:2} del={b} role={c:3}")
    print(f"TOTAL files={len(planned)} subs={total[0]} del={total[1]} roles={total[2]}")

    if not apply:
        print("\n(dry-run; pass --apply to write)")
        return 0

    ts = time.strftime("%Y%m%d-%H%M%S")
    bdir = os.path.join(os.environ.get("TEMP", "."), "kilo", "backups", ts, "library")
    os.makedirs(os.path.dirname(bdir), exist_ok=True)
    shutil.copytree(LIB, bdir)
    print(f"\nbackup -> {bdir}")
    for fn, txt in changed.items():
        io.open(os.path.join(LIB, fn), "wb").write(txt.encode("utf-8"))
    print(f"wrote {len(changed)} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
